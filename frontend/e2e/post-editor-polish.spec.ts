test('keeps replacement status visible after deselection and cancels separately from ordinary uploads', async ({ page }) => {
  await installMockApi(page, { postContents: '<p><img src="https://cdn.noviis.kr/old.png" alt="Original"></p><p>Continue writing</p>' })
  await page.route('https://cdn.noviis.kr/**', route => route.fulfill({ contentType: 'image/png', body: png }))
  let finish!: () => void
  const gate = new Promise<void>(resolve => { finish = resolve })
  await page.route('**/api/v1/files/upload', async route => {
    await gate
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ success: true, data: { fileId: 99, fileUrl: '/api/v1/files/99' } }) }).catch(() => {})
  })
  await login(page)
  await page.goto('/board/general/post/1/edit')
  const editor = page.locator('.ProseMirror')
  const image = editor.locator('.post-editor-image-node > img')
  await image.click()
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: '이미지 교체', exact: true }).click()
  await (await chooser).setFiles({ name: 'replacement.png', mimeType: 'image/png', buffer: png })
  await editor.getByText('Continue writing', { exact: true }).click()
  await expect(page.locator('.image-replacement-status')).toContainText('replacement.png')
  await expect(page.getByRole('button', { name: '수정 완료', exact: true }).first()).toBeDisabled()
  await page.locator('input[type="file"][multiple]').setInputFiles({ name: 'ordinary.png', mimeType: 'image/png', buffer: png })
  await expect(page.locator('.image-upload-status').filter({ hasText: 'ordinary.png' })).toBeVisible()
  await page.getByRole('button', { name: '이미지 교체 취소', exact: true }).click()
  await expect(page.locator('.image-replacement-status')).toHaveCount(0)
  await expect(page.locator('.image-upload-status').filter({ hasText: 'ordinary.png' })).toBeVisible()
  await expect(page.getByRole('button', { name: '수정 완료', exact: true }).first()).toBeDisabled()
  await page.locator('.image-upload-status').getByRole('button', { name: '취소', exact: true }).click()
  await expect(page.getByRole('button', { name: '수정 완료', exact: true }).first()).toBeEnabled()
  await expect(image).toHaveAttribute('src', 'https://cdn.noviis.kr/old.png')
  finish()
})

test('format controls follow code, media and text selections', async ({ page }) => {
  await installMockApi(page, { postContents: '<pre><code>const value = 1</code></pre><p>Normal text</p><p><img src="https://cdn.noviis.kr/old.png" alt="Original"></p>' })
  await page.route('https://cdn.noviis.kr/**', route => route.fulfill({ contentType: 'image/png', body: png }))
  await login(page)
  await page.goto('/board/general/post/1/edit')
  const editor = page.locator('.ProseMirror')
  const toolbar = page.locator('.tiptap-toolbar')
  const bold = toolbar.getByRole('button', { name: '굵게', exact: true })
  const size = toolbar.getByRole('combobox', { name: '글자 크기', exact: true })
  await editor.locator('pre').click()
  await expect(bold).toBeDisabled()
  await expect(size).toBeDisabled()
  await editor.locator('.post-editor-image-node > img').click()
  await expect(bold).toBeDisabled()
  await expect(size).toBeDisabled()
  await editor.getByText('Normal text', { exact: true }).click()
  await expect(bold).toBeEnabled()
  await expect(size).toBeEnabled()
  await page.keyboard.press('Home')
  await page.keyboard.press('Shift+End')
  await bold.click()
  await expect(editor.locator('strong')).toHaveText('Normal text')
})


test('image links can be added, updated and removed without replacing the image', async ({ page }) => {
  await installMockApi(page, { postContents: '<p><img src="https://cdn.noviis.kr/old.png" alt="Original"></p><pre><code>code</code></pre>' })
  await page.route('https://cdn.noviis.kr/**', route => route.fulfill({ contentType: 'image/png', body: png }))
  await login(page)
  await page.goto('/board/general/post/1/edit')
  const editor = page.locator('.ProseMirror')
  const image = editor.locator('.post-editor-image-node > img')
  const link = page.locator('.tiptap-toolbar').getByRole('button', { name: '링크', exact: true })
  const dialog = page.getByRole('dialog', { name: '링크 설정', exact: true })
  for (const url of ['https://first.example/', 'https://updated.example/']) {
    await image.click()
    await expect(link).toBeEnabled()
    await link.click()
    await dialog.locator('#editor-link-url').fill(url)
    await dialog.locator('#editor-link-url').press('Enter')
    await expect(editor.locator('a')).toHaveAttribute('href', url)
    await expect(image).toHaveAttribute('src', 'https://cdn.noviis.kr/old.png')
  }
  await image.click()
  await link.click()
  await dialog.getByRole('button', { name: '링크 제거', exact: true }).click()
  await expect(editor.locator('a')).toHaveCount(0)
  await expect(image).toHaveAttribute('alt', 'Original')
  await editor.locator('pre').click()
  await expect(link).toBeDisabled()
})
