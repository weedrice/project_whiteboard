import { expect, test } from '@playwright/test'
import { installMockApi, login } from './fixtures/mockApi'

for (const width of [390, 1280]) {
  test(`formatting tools preserve text, table styles and code language at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await installMockApi(page, { postContents: '<p><strong>Heading</strong></p><pre><code class="language-c++">int main() {}</code></pre><table><tbody><tr><td colwidth="100"><p>Alpha</p></td><td colwidth="200"><p>Beta</p></td></tr></tbody></table>' })
    await login(page)
    await page.goto('/board/general/post/1/edit')
    const editor = page.locator('.ProseMirror')
    await editor.getByText('Heading', { exact: true }).click()
    await page.getByRole('combobox', { name: '본문 스타일', exact: true }).selectOption('3')
    await expect(editor.locator('h3')).toHaveText('Heading')
    await page.getByRole('button', { name: '실행 취소', exact: true }).click()
    await expect(editor.locator('h3')).toHaveCount(0)
    await page.getByRole('button', { name: '다시 실행', exact: true }).click()
    await expect(editor.locator('h3')).toHaveText('Heading')
    await editor.locator('h3').click()
    await page.keyboard.press('Home')
    await page.keyboard.press('Shift+End')
    await page.getByRole('button', { name: '서식 초기화', exact: true }).click()
    await expect(editor.locator('h3 strong')).toHaveCount(0)
    await expect(editor.locator('h3')).toHaveText('Heading')

    await editor.locator('pre').click()
    const languages = page.getByRole('combobox', { name: '코드 언어', exact: true })
    await expect(languages).toHaveValue('c++')
    await expect(languages.locator('option:checked')).toHaveText('C++')
    await languages.selectOption('rust')
    await expect(editor.locator('code')).toHaveClass('language-rust')

    await editor.getByText('Alpha', { exact: true }).click()
    await page.getByRole('combobox', { name: '셀 배경색', exact: true }).selectOption('#dbeafe')
    await expect(editor.locator('td').first()).toHaveCSS('background-color', 'rgb(219, 234, 254)')
    await page.getByRole('button', { name: '열 너비 균등 분배', exact: true }).click()
    const widths = await editor.locator('td').evaluateAll(cells => cells.map(cell => cell.getAttribute('colwidth')))
    expect(widths[0]).toBe(widths[1])
    expect(Number(widths[0])).toBeGreaterThanOrEqual(40)
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
    await page.getByRole('button', { name: '수정 완료', exact: true }).first().click()
    await page.waitForURL(/\/board\/general\/post\/1\/?$/)
    await page.goto('/board/general/post/1/edit')
    await expect(editor.locator('h3')).toHaveText('Heading')
    await expect(editor.locator('code')).toHaveClass('language-rust')
    await expect(editor.locator('td').first()).toHaveCSS('background-color', 'rgb(219, 234, 254)')
    await expect(editor.locator('td').first()).toHaveAttribute('colwidth', widths[0]!)
    await expect(page.locator('.raw-html-block')).toHaveCount(0)
  })
}
