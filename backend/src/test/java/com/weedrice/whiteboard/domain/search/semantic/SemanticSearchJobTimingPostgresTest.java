package com.weedrice.whiteboard.domain.search.semantic;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;

import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.time.Clock;
import java.time.Instant;
import java.time.LocalDateTime;
import java.time.ZoneId;
import java.time.ZoneOffset;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

@EnabledIfEnvironmentVariable(named = "POSTGRES_SMOKE_TEST", matches = "true")
class SemanticSearchJobTimingPostgresTest {
    private Connection connection;
    private JdbcTemplate jdbc;
    private SemanticSearchJobRepository jobs;
    private final MutableClock clock = new MutableClock();

    @BeforeEach
    void setUp() throws Exception {
        connection = DriverManager.getConnection(
                System.getenv("POSTGRES_SMOKE_DATASOURCE_URL"),
                System.getenv("POSTGRES_SMOKE_DATASOURCE_USERNAME"),
                System.getenv("POSTGRES_SMOKE_DATASOURCE_PASSWORD"));
        connection.setAutoCommit(false);
        jdbc = new JdbcTemplate(new SingleConnectionDataSource(connection, true));
        String schema = "semantic_timing_" + UUID.randomUUID().toString().replace("-", "");
        jdbc.execute("CREATE SCHEMA " + schema);
        jdbc.execute("SET LOCAL search_path TO " + schema + ", public");
        // Exercise the actual upgrade from the old job table, including old-JAR inserts.
        jdbc.execute("""
                CREATE TABLE semantic_search_jobs (
                    job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    content_type VARCHAR(20) NOT NULL, content_id BIGINT NOT NULL,
                    action VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL,
                    retry_count INTEGER NOT NULL, processing_started_at TIMESTAMP(6),
                    completed_at TIMESTAMP(6), last_error_message VARCHAR(500),
                    created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
                    UNIQUE(content_type, content_id))
                """);
        try (var in = getClass().getClassLoader().getResourceAsStream(
                "db/migration/V102__semantic_search_job_timing.sql")) {
            assertThat(in).isNotNull();
            jdbc.execute(new String(in.readAllBytes(), StandardCharsets.UTF_8));
        }
        clock.current = Instant.parse("2026-11-05T00:00:00Z");
        jobs = new SemanticSearchJobRepository(jdbc, clock);
    }

    @AfterEach
    void tearDown() throws Exception {
        if (connection != null) {
            try { connection.rollback(); } finally { connection.close(); }
        }
    }

    @Test
    void reenqueueResetsQueueAgeAndLeaseButPreservesRowCreationHistory() {
        jobs.enqueue("POST", 1L, SemanticSearchIndexAction.UPSERT);
        var original = jobs.findPendingJobs(5, 20).getFirst();
        LocalDateTime created = now();
        jobs.claimForProcessing(original.jobId(), 5, created);
        jobs.markCompleted(original.jobId(), created, created);
        clock.advanceSeconds(86_400 * 30);
        jobs.enqueue("POST", 1L, SemanticSearchIndexAction.UPSERT);
        assertThat(jobs.findOldestPendingCreatedAt()).contains(now());
        assertThat(time("created_at")).isEqualTo(created);
        assertThat(time("next_attempt_at")).isEqualTo(now());
        assertThat(jobs.markCompleted(original.jobId(), created, now())).isZero();
    }

    @Test
    void scheduledRetryCannotBeSelectedOrClaimedEarlyAndKeepsInitialQueueAge() {
        jobs.enqueue("POST", 1L, SemanticSearchIndexAction.UPSERT);
        var job = jobs.findPendingJobs(5, 20).getFirst();
        LocalDateTime queued = now();
        jobs.claimForProcessing(job.jobId(), 5, queued);
        clock.advanceSeconds(10);
        LocalDateTime retryAt = now().plusMinutes(7);
        jobs.markFailedIfCurrent(job.jobId(), queued, 5, "RATE_LIMITED", true, retryAt);
        assertThat(jobs.findPendingJobs(5, 20)).isEmpty();
        assertThat(jobs.claimForProcessing(job.jobId(), 5, now())).isZero();
        assertThat(jobs.findOldestPendingCreatedAt()).contains(queued);
        clock.advanceSeconds(420);
        assertThat(jobs.findPendingJobs(5, 20)).hasSize(1);
        assertThat(jobs.claimForProcessing(job.jobId(), 5, now())).isEqualTo(1);
        assertThat(jobs.findClaimed(job.jobId(), now()).orElseThrow().retryCount()).isEqualTo(1);
    }

    @Test
    void permanentFailureIsTerminalAndAnOldWorkerCannotOverwriteANewRequest() {
        jobs.enqueue("POST", 1L, SemanticSearchIndexAction.UPSERT);
        var job = jobs.findPendingJobs(5, 20).getFirst();
        LocalDateTime lease = now();
        jobs.claimForProcessing(job.jobId(), 5, lease);
        jobs.markFailedIfCurrent(job.jobId(), lease, 5, "HTTP_401", false, now().plusMinutes(1));
        assertThat(jobs.countFailedJobs()).isEqualTo(1);
        assertThat(jobs.findPendingJobs(5, 20)).isEmpty();
        assertThat(time("next_attempt_at")).isNull();
        clock.advanceSeconds(30);
        jobs.enqueue("POST", 1L, SemanticSearchIndexAction.DELETE);
        assertThat(jobs.markFailedIfCurrent(job.jobId(), lease, 5, "late", false, now())).isZero();
        assertThat(jobs.findPendingDeletionJobs(5, 20)).singleElement()
                .extracting(SemanticSearchJob::action).isEqualTo("DELETE");
    }

    @Test
    void legacyInsertRemainsRunnableAndItsQueueAgeUsesLastUpdate() {
        jdbc.update("""
                INSERT INTO semantic_search_jobs
                    (content_type, content_id, action, status, retry_count, created_at, updated_at)
                VALUES ('POST', 1, 'UPSERT', 'PENDING', 0, ?, ?)
                """, now().minusMonths(1), now());
        assertThat(jobs.findPendingJobs(5, 20)).hasSize(1);
        assertThat(jobs.findOldestPendingCreatedAt()).contains(now());
    }

    @Test
    void oldApplicationReenqueueOverridesObsoleteRetryDeadlineAfterRollback() {
        jobs.enqueue("POST", 1L, SemanticSearchIndexAction.UPSERT);
        var job = jobs.findPendingJobs(5, 20).getFirst();
        jobs.claimForProcessing(job.jobId(), 5, now());
        jobs.markFailedIfCurrent(job.jobId(), now(), 5, "RATE_LIMITED", true, now().plusHours(8));
        clock.advanceSeconds(30);
        // The previous JAR does not know about queued_at or next_attempt_at.
        jdbc.update("UPDATE semantic_search_jobs SET status='PENDING', retry_count=0, "
                + "processing_started_at=NULL, last_error_message=NULL, updated_at=? WHERE job_id=?", now(), job.jobId());
        assertThat(jobs.findPendingJobs(5, 20)).hasSize(1);
        assertThat(jobs.findOldestPendingCreatedAt()).contains(now());
        assertThat(jobs.claimForProcessing(job.jobId(), 5, now())).isEqualTo(1);
        assertThat(time("queued_at")).isEqualTo(now());
    }

    @Test
    void staleRecoveryAndDeleteRedriveRespectTiming() {
        jobs.enqueue("POST", 1L, SemanticSearchIndexAction.DELETE);
        var job = jobs.findPendingDeletionJobs(5, 20).getFirst();
        jobs.claimForProcessing(job.jobId(), 5, now());
        clock.advanceSeconds(900);
        assertThat(jobs.recoverStaleProcessingJobs(now().minusMinutes(10), 5, "lease expired")).isEqualTo(1);
        assertThat(jobs.findPendingDeletionJobs(5, 20)).isEmpty();
        clock.advanceSeconds(60);
        assertThat(jobs.findPendingDeletionJobs(5, 20)).hasSize(1);
        jobs.claimForProcessing(job.jobId(), 5, now());
        jobs.markFailedIfCurrent(job.jobId(), now(), 5, "terminal", false, now());
        clock.advanceSeconds(60);
        assertThat(jobs.redriveFailedDeletes("POST", 1)).isEqualTo(1);
        assertThat(jobs.findOldestPendingCreatedAt()).contains(now());
        assertThat(jobs.findPendingDeletionJobs(5, 20)).hasSize(1);
    }

    private LocalDateTime time(String column) {
        return jdbc.queryForObject("SELECT " + column + " FROM semantic_search_jobs WHERE content_id=1",
                LocalDateTime.class);
    }
    private LocalDateTime now() { return LocalDateTime.now(clock); }
    private static class MutableClock extends Clock {
        private Instant current;
        void advanceSeconds(long seconds) { current = current.plusSeconds(seconds); }
        @Override public ZoneId getZone() { return ZoneOffset.UTC; }
        @Override public Clock withZone(ZoneId zone) { return Clock.fixed(current, zone); }
        @Override public Instant instant() { return current; }
    }
}
