package com.weedrice.whiteboard.domain.file.repository;

import com.weedrice.whiteboard.domain.emoticon.entity.EmoticonImage;
import com.weedrice.whiteboard.domain.emoticon.entity.EmoticonMaster;
import com.weedrice.whiteboard.domain.emoticon.entity.EmoticonPurchase;
import com.weedrice.whiteboard.domain.file.entity.File;
import com.weedrice.whiteboard.domain.file.entity.FileStorageStatus;
import com.weedrice.whiteboard.domain.file.service.FileService;
import com.weedrice.whiteboard.domain.post.scheduled.entity.ScheduledPostFile;
import com.weedrice.whiteboard.domain.user.entity.User;
import com.weedrice.whiteboard.global.config.QuerydslConfig;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.boot.jpa.test.autoconfigure.TestEntityManager;
import org.springframework.context.annotation.Import;
import org.springframework.test.context.jdbc.Sql;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

@DataJpaTest
@Import(QuerydslConfig.class)
@Sql(statements = """
        CREATE TABLE IF NOT EXISTS emoticon_masters (
            is_active VARCHAR(1) NOT NULL,
            purchase_count INTEGER NOT NULL,
            created_at TIMESTAMP(6) NOT NULL,
            creator_id BIGINT,
            emoticon_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            modified_at TIMESTAMP(6) NOT NULL,
            name VARCHAR(100) NOT NULL,
            thumbnail_url VARCHAR(500),
            tags VARCHAR ARRAY
        );
        """)
class EmoticonContentFileReferenceTest {
    @Autowired private TestEntityManager entityManager;
    @Autowired private FileRepository fileRepository;

    private User creator;
    private User buyer;
    private User outsider;
    private EmoticonMaster master;

    @BeforeEach
    void setUp() {
        creator = user("creator");
        buyer = user("buyer");
        outsider = user("outsider");
        master = entityManager.persist(EmoticonMaster.builder().creator(creator)
                .name("Post emoticons").tags(List.of()).build());
        entityManager.persist(EmoticonPurchase.builder().user(buyer).emoticon(master).purchasedPrice(100).build());
    }

    @Test
    void activePackIsUsableOnlyByCreatorOrBuyerIncludingImagesRemovedFromPicker() {
        File image = file(master.getEmoticonId(), FileService.RELATED_TYPE_EMOTICON_IMAGE);
        entityManager.flush();

        assertThat(usable(creator, image)).containsExactly(image.getFileId());
        assertThat(usable(buyer, image)).containsExactly(image.getFileId());
        assertThat(usable(outsider, image)).isEmpty();
        assertThat(master.getImages()).isEmpty();
    }

    @Test
    void hiddenPackKeepsCreatorAndBuyerUseRights() {
        master.deactivate();
        File image = file(master.getEmoticonId(), FileService.RELATED_TYPE_EMOTICON_IMAGE);
        entityManager.flush();

        assertThat(usable(creator, image)).containsExactly(image.getFileId());
        assertThat(usable(buyer, image)).containsExactly(image.getFileId());
        assertThat(usable(outsider, image)).isEmpty();
    }

    @Test
    void unassociatedLegacyImagesRequireAnActualImageRecord() {
        File canonical = file(null, null);
        File legacy = file(null, null);
        File thumbnail = file(null, null);
        File unrelated = file(null, null);
        master.addImage(EmoticonImage.builder().imageUrl("/api/v1/files/" + canonical.getFileId()).sortOrder(0).build());
        master.addImage(EmoticonImage.builder().imageUrl("/files/" + legacy.getFileId()).sortOrder(1).build());
        master.update(master.getName(), "/api/v1/files/" + thumbnail.getFileId(), List.of());
        entityManager.flush();

        assertThat(usable(buyer, canonical, legacy, thumbnail, unrelated))
                .containsExactlyInAnyOrder(canonical.getFileId(), legacy.getFileId());
    }

    @Test
    void deletionAndScheduledReservationsCannotBeBypassedByEmoticonReferences() {
        File deleted = file(master.getEmoticonId(), FileService.RELATED_TYPE_EMOTICON_IMAGE);
        File reserved = file(master.getEmoticonId(), FileService.RELATED_TYPE_EMOTICON_IMAGE);
        deleted.markDeletionPending(java.time.LocalDateTime.now());
        entityManager.persist(new ScheduledPostFile(77L, reserved.getFileId(), 0));
        entityManager.flush();

        assertThat(usable(buyer, deleted, reserved)).isEmpty();
        assertThat(deleted.getStorageStatus()).isEqualTo(FileStorageStatus.PENDING_DELETE);
    }

    @Test
    void ordinaryAttachmentsAndThumbnailsCannotBeReclassifiedAsEmoticonImages() {
        File post = file(91L, FileService.RELATED_TYPE_POST_CONTENT);
        File draft = file(92L, FileService.RELATED_TYPE_DRAFT_POST);
        File thumbnail = file(master.getEmoticonId(), FileService.RELATED_TYPE_EMOTICON_THUMBNAIL);
        for (File file : List.of(post, draft, thumbnail)) {
            master.addImage(EmoticonImage.builder().imageUrl("/api/v1/files/" + file.getFileId()).sortOrder(0).build());
        }
        entityManager.flush();

        assertThat(usable(creator, post, draft, thumbnail)).isEmpty();
    }

    private List<Long> usable(User user, File... files) {
        return fileRepository.findUsableEmoticonImageFileIds(
                java.util.Arrays.stream(files).map(File::getFileId).toList(), user.getUserId());
    }

    private User user(String name) {
        return entityManager.persist(User.builder().loginId("emoticon-content-" + name)
                .email("emoticon-content-" + name + "@example.test").password("test-only")
                .displayName(name).build());
    }

    private File file(Long relatedId, String relatedType) {
        return entityManager.persist(File.builder().originalName("image.png").filePath("emoticon/image.png")
                .mimeType("image/png").fileSize(10L).uploader(creator)
                .relatedId(relatedId).relatedType(relatedType).build());
    }
}
